#!/usr/bin/env python3
"""Deploy the workshop's case template (SOC playbook) and custom observable types.

Reads assets/case-template.json and assets/observable-types.json, both generated by the guide
builder (../build_walkthrough.py) so the template always matches the guide. Idempotent: the
template is created or updated by name; missing observable types are added.

Env: KIBANA_URL, KIBANA_API_KEY (or ELASTICSEARCH_API_KEY).
"""
from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request
import uuid

ASSETS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")


def kb(method, path, body=None, version="1"):
    base = os.environ.get("KIBANA_URL", "").rstrip("/")
    key = os.environ.get("KIBANA_API_KEY") or os.environ.get("ELASTICSEARCH_API_KEY", "")
    r = urllib.request.Request(base + path, method=method,
                               data=json.dumps(body).encode() if body is not None else None, headers={
        "Authorization": f"ApiKey {key}", "Content-Type": "application/json", "kbn-xsrf": "true",
        "x-elastic-internal-origin": "Kibana", "elastic-api-version": version})
    try:
        with urllib.request.urlopen(r) as resp:
            raw = resp.read()
            return resp.status, (json.loads(raw) if raw else {})
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()[:300]


def template(api):
    s, t = kb("GET", "/internal/cases/templates?owner=securitySolution")
    tid = None
    if s == 200:
        tid = next((x.get("templateId") or x.get("id") for x in t.get("templates", [])
                    if x["name"] == api["name"] and x.get("isLatest", True)), None)
    if tid:
        for method in ("PUT", "PATCH"):
            s, b = kb(method, f"/internal/cases/templates/{tid}", api)
            if s == 200:
                print(f"  template '{api['name']}' updated via {method} ({tid})")
                return True
            print(f"  {method} template: HTTP {s} {b}")
        return False
    s, b = kb("POST", "/internal/cases/templates", api)
    print(f"  template '{api['name']}' created: HTTP {s} {'' if s == 200 else b}")
    return s == 200


def observable_types(types):
    # Stable keys, so re-runs and other clusters agree.
    want = [{"key": str(uuid.uuid5(uuid.NAMESPACE_URL, f"elasticon/{t['key']}")), "label": t["label"]}
            for t in types]
    s, cfg = kb("GET", "/api/cases/configure?owner=securitySolution", version="2023-10-31")
    if s != 200:
        print(f"  observable types: GET configure HTTP {s} {cfg}")
        return False
    if not cfg:
        s, b = kb("POST", "/api/cases/configure", {
            "owner": "securitySolution", "closure_type": "close-by-user",
            "connector": {"id": "none", "name": "none", "type": ".none", "fields": None},
            "observableTypes": want}, version="2023-10-31")
        print(f"  observable types: created configuration with {len(want)} custom types (HTTP {s})")
        return s == 200
    c = cfg[0]
    have = {t["label"]: t for t in c.get("observableTypes") or []}
    merged = list(have.values()) + [t for t in want if t["label"] not in have]
    if len(merged) == len(have):
        print(f"  observable types: all {len(want)} custom types present")
        return True
    s, b = kb("PATCH", f"/api/cases/configure/{c['id']}", {"version": c["version"], "observableTypes": merged},
              version="2023-10-31")
    print(f"  observable types: {len(merged) - len(have)} added (HTTP {s}{'' if s == 200 else ' ' + str(b)})")
    return s == 200


def main():
    if not os.environ.get("KIBANA_URL"):
        sys.exit("KIBANA_URL not set — source env.sh")
    api = json.load(open(os.path.join(ASSETS, "case-template.json")))
    types = json.load(open(os.path.join(ASSETS, "observable-types.json")))
    ok = template(api) & observable_types(types)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
